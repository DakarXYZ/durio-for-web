/**
 * Generate the API library from OpenAPI.json (WEB-01).
 *
 * A port of the `@insertish/oapi` CLI (MIT) that upstream `stoat-api` is built with, so the
 * output has the same shape: src/schema.ts (openapi-typescript), routes.ts, params.ts,
 * types.ts and baseURL.ts. src/index.ts (the `API` class) is not generated.
 * `anyOf` is rewritten to `oneOf` like upstream's `REWRITE_ANYOF=1`.
 *
 *   pnpm --filter @durio/stoat-api generate && pnpm --filter @durio/stoat-api build
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapi from "openapi-typescript";

const root = dirname(fileURLToPath(import.meta.url));
const NOTICE = `// This file was auto-generated by codegen.mjs from OpenAPI.json!\n`;

const out = (name, data) => writeFile(resolve(root, "src", name), data);

const source = (await readFile(resolve(root, "OpenAPI.json")))
  .toString()
  .replace(/"anyOf"/g, '"oneOf"');
const spec = JSON.parse(source);

// Schema
await out("schema.ts", await openapi(spec));

// Route types and data
{
  const entries = [
    "import { paths } from './schema';",
    "export type APIRoutes =",
  ];
  const paths = Object.keys(spec.paths);
  const queryData = {};

  for (const path of paths) {
    const data = spec.paths[path];
    const template = path.replace(/\{\w+\}/g, "${string}");

    for (const method of Object.keys(data)) {
      const OPERATION = `paths['${path}']['${method}']`;

      const route = data[method];
      const response =
        Object.keys(route["responses"]).find((x) => x !== "default") ||
        "default";
      const contentType = Object.keys(
        route["responses"][response]["content"] || {},
      )[0];
      const RESPONSE =
        response === "204" || !contentType
          ? "undefined"
          : `${OPERATION}['responses']['${response}']['content']['${contentType}']`;

      const queryParams = [];
      for (const parameter of route["parameters"] ?? [])
        if (parameter.in === "query") queryParams.push(parameter.name);

      const hasBody = !!route["requestBody"]?.["content"]?.["application/json"];

      let params = "undefined";
      if (hasBody || queryParams.length > 0) {
        const types = [];
        if (queryParams.length > 0)
          types.push(`${OPERATION}['parameters']['query']`);
        if (hasBody)
          types.push(
            `${OPERATION}['requestBody']['content']['application/json']`,
          );
        params = types.join("|");
      }

      const parts = path.split("").filter((x) => x === "/").length;
      entries.push(
        `| { method: '${method}', path: \`${template}\`, parts: ${parts}, params: ${params}, response: ${RESPONSE} }`,
      );

      if (/\{\w+\}/.test(path))
        entries.push(
          `| { method: '${method}', path: '-${path}', parts: ${parts}, params: ${params}, response: ${RESPONSE} }`,
        );

      queryData[path] = { ...queryData[path], [method]: queryParams };
    }
  }

  const pathResolve = {};
  for (const path of paths) {
    const segments = path.split("/");
    segments.shift();
    pathResolve[segments.length] = [
      ...(pathResolve[segments.length] || []),
      segments.map((key) => (/\{.*\}/.test(key) ? [key] : key)),
    ];
  }

  await out("routes.ts", NOTICE + entries.join("\n") + ";");
  await out(
    "params.ts",
    NOTICE +
      "export const pathResolve = " +
      JSON.stringify(pathResolve) +
      ";\n" +
      "export const queryParams = " +
      JSON.stringify(queryData) +
      ";",
  );
}

// Type exports
await out(
  "types.ts",
  NOTICE +
    ["import { components } from './schema';"]
      .concat(
        Object.keys(spec.components.schemas).map(
          (schema) =>
            `export type ${schema.replace(/\s/g, "_")} = components['schemas']['${schema}'];`,
        ),
      )
      .join("\n") +
    ";",
);

// Default base URL
const baseURL = spec["servers"]?.[0]?.["url"];
await out(
  "baseURL.ts",
  NOTICE +
    `export const defaultBaseURL = ${baseURL ? '"' + baseURL + '"' : "undefined"};`,
);
